import numpy as np

# Create float array
arr = np.array([10.5, 20.75, 30.25, 40.90, 50.10], dtype=float)

print("Array:", arr)
print("Data Type:", arr.dtype)

# Mathematical operations
print("Sum:", np.sum(arr))
print("Average:", np.mean(arr))
print("Maximum:", np.max(arr))
print("Minimum:", np.min(arr))